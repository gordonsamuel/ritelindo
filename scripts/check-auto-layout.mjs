import assert from 'node:assert/strict';
import {autoLayout,catalogLayout,catalogInventory} from '../src/auto-layout.mjs';
import {catalogSpec} from '../src/rack-catalog.mjs';
import {assess,footprint,overlaps} from '../src/planner-math.mjs';
const room={width:8,depth:10,height:2.8};
const inventory=[catalogSpec('single-30',90,35,180),catalogSpec('double-30',90,65,180),catalogSpec('cashier-standard',150,60,90),...Array.from({length:5},()=>catalogSpec('shopping-hand',46.3,34,22.5))].map((r,i)=>({...r,id:i+1,x:3,z:3,rotated:false}));
const result=autoLayout(room,inventory,.6);
assert.equal(result.failed.length,0);assert.equal(result.racks.length,8);assert.equal(result.aisle,1.2);
assert.equal(result.racks.filter(r=>r.stackTo).length,4);
assert.equal(assess(room,result.racks,result.aisle).issues.length,0);
for(const r of result.racks.filter(r=>!r.stackTo))assert.equal(overlaps(footprint(r),result.corridor),false);
assert.ok(autoLayout({width:3,depth:3,height:2.8},inventory,1.2).failed.length>0);
assert.equal(inventory.some(r=>r.stackTo),false);
const overflow=autoLayout(room,Array.from({length:15},(_,i)=>({...inventory[3],id:i+1})),1.2);assert.ok(overflow.failed.length>0);
console.log('PASS: mixed inventory preserved, central route clear, minimum aisle, basket stacking, height limit, insufficient space and immutable input');
const all=catalogLayout({width:6,depth:8,height:2.8},1.2);
assert.equal(catalogInventory().length,24);assert.equal(all.racks.length,24);assert.equal(all.failed.length,0);
assert.equal(new Set(all.racks.map(r=>r.productId)).size,21);
assert.equal(assess(all.room,all.racks,all.aisle).issues.length,0);
for(const r of all.racks.filter(r=>!r.stackTo&&!r.attachTo))assert.equal(overlaps(footprint(r),all.corridor),false);
console.log('PASS: whole catalog, all 21 variants, 24 objects, four baskets, automatic example-room sizing and clear circulation');
